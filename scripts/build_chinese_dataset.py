def generate_chinese_dataset():
    ko_path = DATA_DIR / 'ko' / 'koreanData.ts'
    with open(ko_path, 'r', encoding='utf-8') as f:
        ko_content = f.read()

    cw_match = re.search(r'const commonWords: PhraseItem\[\] = \[(.*?)\];\s*// Korean Time', ko_content, re.DOTALL)
    if not cw_match:
        print("Error: could not parse commonWords from koreanData.ts")
        sys.exit(1)

    raw_items = re.findall(r"\{\s*phrase:\s*'((?:\\'|[^'])+)',\s*translation:\s*'((?:\\'|[^'])+)',\s*pronunciation:\s*'((?:\\'|[^'])*)',\s*category:\s*'((?:\\'|[^'])+)',\s*icon:\s*'((?:\\'|[^'])+)'\s*\}", cw_match.group(1))
    ko_items = [(p.replace("\\'", "'"), t.replace("\\'", "'"), pr.replace("\\'", "'"), c.replace("\\'", "'"), ic.replace("\\'", "'")) for p, t, pr, c, ic in raw_items]

    print(f"Loaded {len(ko_items)} reference items from Korean.")

    zh_common_words = []
    missing = []

    for phrase, translation, pron, category, icon in ko_items:
        clean_tr = translation.strip()
        zh_tuple = ZH_DICTIONARY.get(clean_tr)

        if not zh_tuple:
            zh_tuple = ZH_DICTIONARY.get(clean_tr.capitalize()) or ZH_DICTIONARY.get(clean_tr.title())

        if zh_tuple:
            zh_phrase, zh_pron = zh_tuple
            zh_common_words.append({
                "phrase": zh_phrase,
                "translation": clean_tr,
                "pronunciation": zh_pron,
                "category": category,
                "icon": icon
            })
        else:
            missing.append(clean_tr)

    if missing:
        print(f"WARNING: Still missing {len(missing)} translations:")
        for m in missing:
            print(f"  - {m}")
        sys.exit(1)

    print(f"All {len(zh_common_words)} Chinese common words successfully mapped with 0 gaps!")

    def q(s: str) -> str:
        return s.replace("\\", "\\\\").replace("'", "\\'")

    output_lines = [
        "import { AlphabetItem, PhraseItem, AppData } from '../../../types';",
        "import { CHINESE_GRAMMAR } from '../grammarData';",
        "",
        "// Mandarin Chinese Pinyin Alphabet (Initials, Finals & Core Sounds)",
        "const alphabet: AlphabetItem[] = ["
    ]

    for letter, pron, ex, word, meaning, icon in ALPHABET_DATA:
        output_lines.append(f"  {{ letter: '{q(letter)}', pronunciation: '{q(pron)}', example: '{q(ex)}', word: '{q(word)}', meaning: '{q(meaning)}', icon: '{q(icon)}' }},")
    output_lines.append("];")
    output_lines.append("")

    output_lines.append("// Essential Chinese Phrases")
    output_lines.append("const basicPhrases: PhraseItem[] = [")
    for ph, tr, pron, cat, icon in PHRASES_DATA:
        output_lines.append(f"  {{ phrase: '{q(ph)}', translation: '{q(tr)}', pronunciation: '{q(pron)}', category: '{q(cat)}', icon: '{q(icon)}' }},")
    output_lines.append("];")
    output_lines.append("")

    output_lines.append("// Chinese Numbers")
    output_lines.append("const numbers: PhraseItem[] = [")
    for ph, tr, pron, cat, icon in NUMBERS_DATA:
        output_lines.append(f"  {{ phrase: '{q(ph)}', translation: '{q(tr)}', pronunciation: '{q(pron)}', category: '{q(cat)}', icon: '{q(icon)}' }},")
    output_lines.append("];")
    output_lines.append("")

    output_lines.append("// Core Chinese Vocabulary (500+ items across all categories)")
    output_lines.append("const commonWords: PhraseItem[] = [")
    for item in zh_common_words:
        p_ph = q(item['phrase'])
        p_tr = q(item['translation'])
        p_pr = q(item['pronunciation'])
        p_cat = q(item['category'])
        p_ic = q(item['icon'])
        output_lines.append(f"  {{ phrase: '{p_ph}', translation: '{p_tr}', pronunciation: '{p_pr}', category: '{p_cat}', icon: '{p_ic}' }},")
    output_lines.append("];")
    output_lines.append("")

    output_lines.append("// Chinese Time expressions")
    output_lines.append("const time: PhraseItem[] = [")
    for ph, tr, pron, cat, icon in TIME_DATA:
        output_lines.append(f"  {{ phrase: '{q(ph)}', translation: '{q(tr)}', pronunciation: '{q(pron)}', category: '{q(cat)}', icon: '{q(icon)}' }},")
    output_lines.append("];")
    output_lines.append("")

    output_lines.append("export const chineseData: AppData = {")
    output_lines.append("  alphabet,")
    output_lines.append("  basicPhrases,")
    output_lines.append("  numbers,")
    output_lines.append("  commonWords,")
    output_lines.append("  time,")
    output_lines.append("  grammar: CHINESE_GRAMMAR,")
    output_lines.append("};")
    output_lines.append("")
    output_lines.append("export default chineseData;")
    output_lines.append("")

    out_file = ZH_DIR / 'chineseData.ts'
    with open(out_file, 'w', encoding='utf-8') as f:
        f.write("\n".join(output_lines))

    print(f"Successfully generated {out_file} ({len(output_lines)} lines).")

if __name__ == '__main__':
    generate_chinese_dataset()
